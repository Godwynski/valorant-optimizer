use serde::{Deserialize, Serialize};

/// Represents an advanced hardware property of a physical network adapter.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct NicAdvancedProperty {
    #[serde(rename = "DisplayName")]
    pub display_name: String,
    #[serde(rename = "RegistryKeyword")]
    pub registry_keyword: String,
    #[serde(rename = "RegistryValue")]
    pub registry_value: Option<Vec<String>>,
}

impl NicAdvancedProperty {
    /// Helper to get the first registry value as a string slice.
    pub fn first_value(&self) -> Option<&str> {
        self.registry_value.as_ref().and_then(|v| v.first().map(|s| s.as_str()))
    }
}

/// Backup record for an individual adapter property prior to modification,
/// enabling 100% deterministic rollback.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct AdapterPropertyBackup {
    pub adapter_name: String,
    pub keyword: String,
    pub display_name: String,
    pub original_value: String,
}

/// Status of 802.3x Flow Control on the network adapter.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub enum FlowControlSetting {
    Disabled = 0,
    TxEnabled = 1,
    RxEnabled = 2,
    RxTxEnabled = 3,
    Unknown = -1,
}

impl From<i32> for FlowControlSetting {
    fn from(val: i32) -> Self {
        match val {
            0 => FlowControlSetting::Disabled,
            1 => FlowControlSetting::TxEnabled,
            2 => FlowControlSetting::RxEnabled,
            3 => FlowControlSetting::RxTxEnabled,
            _ => FlowControlSetting::Unknown,
        }
    }
}

