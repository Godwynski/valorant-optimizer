/// Standard Bufferbloat Grade (Bufferbloat.net / Flent grading scale).
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub enum BufferbloatGrade {
    APlus,
    A,
    B,
    C,
    D,
    F,
}

impl BufferbloatGrade {
    pub fn from_latency_delta(delta_ms: f64, packet_loss_pct: f64) -> Self {
        if packet_loss_pct > 5.0 {
            return BufferbloatGrade::F;
        }
        if delta_ms < 5.0 {
            BufferbloatGrade::APlus
        } else if delta_ms < 15.0 {
            BufferbloatGrade::A
        } else if delta_ms < 30.0 {
            BufferbloatGrade::B
        } else if delta_ms < 60.0 {
            BufferbloatGrade::C
        } else if delta_ms < 120.0 {
            BufferbloatGrade::D
        } else {
            BufferbloatGrade::F
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            BufferbloatGrade::APlus => "A+",
            BufferbloatGrade::A => "A",
            BufferbloatGrade::B => "B",
            BufferbloatGrade::C => "C",
            BufferbloatGrade::D => "D",
            BufferbloatGrade::F => "F",
        }
    }
}

